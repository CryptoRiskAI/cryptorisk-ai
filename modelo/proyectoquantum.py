# -*- coding: utf-8 -*-
"""
clustering.py — Agrupamiento no supervisado (CryptoRisk AI)

Aplica K-Means sobre los subpuntajes de riesgo (no sobre el Score Total).
Evalúa k=2, 3 y 4 con semilla fija y reporta Silhouette Score.
Los clústeres describen perfiles similares; no sustituyen el Nivel de Riesgo
definido por las reglas (sección 6 del anteproyecto).
"""

import pandas as pd
import numpy as np
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import silhouette_score

# Columnas de subpuntaje que se usarán para el clustering
# (deben coincidir con las claves de PESOS en reglas.py)
COLUMNAS_CLUSTER = [
    "Algoritmo", "Criticidad", "Sensibilidad",
    "Retención (años)", "Exposición", "Migración"
]

def preparar_matriz(df: pd.DataFrame, pesos: dict) -> np.ndarray:
    """Convierte las variables categóricas a sus subpuntajes numéricos
    y las estandariza. Devuelve la matriz lista para K-Means.
    """
    matriz = []
    for _, fila in df.iterrows():
        vector = [pesos[col][fila[col]] for col in COLUMNAS_CLUSTER]
        matriz.append(vector)
    matriz = np.array(matriz)
    scaler = StandardScaler()
    return scaler.fit_transform(matriz)

def evaluar_kmeans(matriz: np.ndarray, k_min: int = 2, k_max: int = 4, semilla: int = 42):
    """Prueba varios valores de k y devuelve el mejor según Silhouette Score
    junto con el modelo entrenado y la tabla de resultados.
    """
    resultados = []
    mejor_score = -1
    mejor_modelo = None
    mejor_k = None
    mejores_etiquetas = None

    for k in range(k_min, k_max + 1):
        modelo = KMeans(n_clusters=k, random_state=semilla, n_init=10)
        etiquetas = modelo.fit_predict(matriz)
        score = silhouette_score(matriz, etiquetas)
        resultados.append({"k": k, "silhouette": round(score, 4)})
        if score > mejor_score:
            mejor_score = score
            mejor_modelo = modelo
            mejor_k = k
            mejores_etiquetas = etiquetas

    tabla = pd.DataFrame(resultados)
    return mejor_k, mejor_modelo, mejores_etiquetas, mejor_score, tabla

def aplicar_clustering(df: pd.DataFrame, pesos: dict) -> pd.DataFrame:
    """Punto de entrada. Recibe el DataFrame ya enriquecido por reglas.py
    y añade la columna 'Cluster'.
    """
    df = df.copy()
    matriz = preparar_matriz(df, pesos)
    k, modelo, etiquetas, sil_score, tabla_k = evaluar_kmeans(matriz)

    df["Cluster"] = etiquetas
    # Información útil para el dashboard
    df.attrs["mejor_k"] = k
    df.attrs["silhouette"] = sil_score
    df.attrs["tabla_k"] = tabla_k

    return df

