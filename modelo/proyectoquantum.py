import pandas as pd

# Mismas reglas de puntuación que en el generador del dataset.
# IMPORTANTE: si el equipo decide ajustar los pesos de 'algoritmos'
# (por ejemplo, acercar SHA-256 y AES-256), este es el único lugar
# donde hay que cambiarlo — no en el generador ni en Streamlit.
PESOS = {
    "Algoritmo": {"RSA-2048": 10, "ECC-P256": 8, "AES-256": 2, "SHA-256": 5, "PQC": 0},
    "Criticidad": {"Alta": 10, "Media": 5, "Baja": 2},
    "Sensibilidad": {"Secreto": 10, "Confidencial": 7, "Interno": 4, "Público": 1},
    "Retención (años)": {">20": 10, "10-20": 7, "5-10": 4, "<5": 1},
    "Exposición": {"Alta": 10, "Media": 5, "Baja": 2},
    "Migración": {"Alta": 10, "Media": 5, "Baja": 2},
}

# Puntaje máximo posible (10+10+10+10+10+10), usado para normalizar
# el score a un rango 0-100 y para definir los umbrales de nivel de riesgo.
SCORE_MAXIMO = sum(max(escala.values()) for escala in PESOS.values())


def calcular_subpuntajes(fila: pd.Series) -> dict:
    """Devuelve el puntaje individual de cada una de las 6 variables de riesgo.

    Útil para el clustering (que debe recibir el vector de subpuntajes,
    no solo el Score Total) y para que el dashboard explique el resultado
    variable por variable.
    """
    return {variable: PESOS[variable][fila[variable]] for variable in PESOS}


def calcular_score(fila: pd.Series) -> int:
    """Score total determinístico: suma de los 6 subpuntajes."""
    subpuntajes = calcular_subpuntajes(fila)
    return sum(subpuntajes.values())


def calcular_score_normalizado(fila: pd.Series) -> float:
    """Score en escala 0-100, más fácil de interpretar en el dashboard."""
    return round(100 * calcular_score(fila) / SCORE_MAXIMO, 1)


def clasificar_nivel_riesgo(score_normalizado: float) -> str:
    """Traduce el score normalizado (0-100) a un nivel de riesgo cualitativo,
    siguiendo el enfoque de escalas de NIST SP 800-30 (Muy Baja/Baja/
    Moderada/Alta/Muy Alta), simplificado a 3 niveles para el MVP.

    Los umbrales (33 / 66) son una decisión de diseño del equipo — deben
    documentarse en la ficha de datos y pueden ajustarse si, al ver la
    distribución real del dataset, no separan bien los grupos.
    """
    if score_normalizado >= 66:
        return "Alto"
    elif score_normalizado >= 33:
        return "Medio"
    else:
        return "Bajo"


def generar_recomendacion(nivel_riesgo: str) -> str:
    """Plantilla determinística de recomendación por nivel de riesgo.

    Nada de IA generativa (excluido explícitamente en la sección 7 del
    anteproyecto) — son plantillas fijas y trazables.
    """
    plantillas = {
        "Alto": (
            "Revisar este activo de forma prioritaria. Evaluar tiempo de "
            "migración frente a los años de retención restantes (criterio "
            "de Mosca, 2018: X + Y > Z)."
        ),
        "Medio": (
            "Incluir en el plan de migración a mediano plazo; monitorear "
            "cambios en criticidad o exposición."
        ),
        "Bajo": (
            "Sin acción inmediata; reevaluar en el próximo ciclo de "
            "inventario criptográfico."
        ),
    }
    return plantillas[nivel_riesgo]


def aplicar_reglas(df: pd.DataFrame) -> pd.DataFrame:
    """Punto de entrada único del módulo: recibe el DataFrame ya validado
    (ver validacion.py) y devuelve una copia enriquecida con:
    Score Total, Score Normalizado, Nivel de Riesgo y Recomendación.
    """
    df = df.copy()
    df["Score Total"] = df.apply(calcular_score, axis=1)
    df["Score Normalizado"] = df.apply(calcular_score_normalizado, axis=1)
    df["Nivel de Riesgo"] = df["Score Normalizado"].apply(clasificar_nivel_riesgo)
    df["Recomendación"] = df["Nivel de Riesgo"].apply(generar_recomendacion)
    return df

